"""Fit a machine profile to its calibration measurements and judge it on the validation split.

    python -m benchmarks.calibrate measurements.json --machine i9-11900kf-3080ti \
        --profile-out configs/i9_11900kf_rtx3080ti.json

1. The **calibration** split of the machine's measurements tunes four parameters of its hardware
   profile (CPU and GPU arithmetic rate and memory bandwidth), with the simulator in the loop.
2. The fitted profile predicts every measurement; only the **validation** split, which the fit
   never saw, decides the verdict (median and 95th-percentile error against the thresholds in
   ``configs/hardware_gate.json``).

Writing the fitted profile over the machine's prior in ``configs/`` makes the report
(``python -m benchmarks.run_report --base-profile <profile>``) use it.  The fit says nothing about
hardware that does not exist: module parameters stay estimates.

Exercised in the development container only on synthetic measurements generated by the simulator
itself (the fit recovers the parameters that produced them).  No real measurement has been fitted.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from basp.calibration import MeasurementSet
from basp.core.topology import Topology
from basp.experiments.calibrate import MACHINE_PROFILES, fit_profile, score
from basp.experiments.profiles import load_json


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("measurements", help="measurement set written by benchmarks.run_llama_bench")
    parser.add_argument("--machine", required=True, help="machine label used in the measurements")
    parser.add_argument("--profile", help="prior profile: a name in configs/ or a path "
                                          "(default: the profile registered for the machine)")  # fmt: skip
    parser.add_argument("--profile-out", help="where to write the fitted profile (JSON)")
    parser.add_argument("--no-fit", action="store_true", help="only score the profile as it is")
    parser.add_argument("--report", help="write the full calibration report (JSON)")
    args = parser.parse_args(argv)

    measurements = MeasurementSet.load(args.measurements)
    problems = measurements.check()
    if problems:
        parser.error("measurement set is inconsistent: " + "; ".join(problems))
    name = args.profile or MACHINE_PROFILES.get(args.machine)
    if name is None:
        parser.error(f"no profile registered for machine {args.machine!r}; pass --profile")
    profile = load_json(name)
    own = [m for m in measurements if m.machine == args.machine]
    n_cal = sum(1 for m in own if m.split == "calibration")
    n_val = len(own) - n_cal
    print(f"{args.machine}: {n_cal} calibration and {n_val} validation measurements; profile {name}")

    if not args.no_fit:
        if not n_cal:
            parser.error("no calibration-split measurements to fit; use --no-fit to score the prior")
        fit = fit_profile(own, args.machine, profile)
        profile = fit.profile
        print(f"fitted on {len(fit.used)} calibration measurements ({fit.evaluations} simulator settings):")
        for parameter, scale in fit.scales.items():
            print(f"  {parameter:22s} x{scale:.3f} of the prior")
        print(f"  in-sample median error {fit.median_error_before:.1%} -> {fit.median_error_after:.1%} "
              "(informational: this is the data the fit was tuned on)")  # fmt: skip
        if args.profile_out:
            Path(args.profile_out).write_text(json.dumps(profile, indent=1) + "\n")
            print(f"wrote {args.profile_out}")

    thresholds = load_json("hardware_gate")
    report = score(
        MeasurementSet(own), {args.machine: Topology.from_dict(profile)},
        median_max=thresholds["calibration_median_max"], p95_max=thresholds["calibration_p95_max"],
        min_validation=thresholds["min_validation_measurements"],
    )  # fmt: skip
    print(f"{'id':32s} {'split':12s} {'measured':>10s} {'predicted':>10s} {'error':>8s}")
    for row in report.per_measurement:
        predicted = f"{row['predicted']:10.2f}" if row["predicted"] is not None else f"{'-':>10s}"
        error = f"{row['rel_error']:8.1%}" if row["rel_error"] is not None else f"{'-':>8s}"
        print(f"{row['id'][:32]:32s} {row['split']:12s} {row['measured']:10.2f} {predicted} {error}")
    v = report.validation
    print(f"validation: {v.n} measurements, median error {v.median:.1%}, p95 {v.p95:.1%} -> "
          f"{report.status.replace('_', ' ').upper()}")  # fmt: skip
    for line in [*report.reasons, *report.notes]:
        print(f"  {line}")
    if args.report:
        Path(args.report).write_text(json.dumps(report.to_json(), indent=1) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
